import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const rootHtml = readFileSync(join('public', 'index.html'), 'utf8');

let html = rootHtml;

html = html.replace(
  '<meta name="viewport" content="width=device-width, initial-scale=1">',
  '<meta name="viewport" content="width=device-width, initial-scale=1">\n  <meta name="robots" content="noindex">',
);

html = html.replace(
  '<title>Convexa — QQQ options book on iPhone</title>',
  '<title>Convexa — QQQ options book on iPhone — IA B</title>',
);

html = html.replace(
  /\s*<link rel="canonical" href="https:\/\/convexa\.today\/">\n/g,
  '',
);
html = html.replace(/\s*<meta property="og:[^"]+"[^>]*>\n/g, '');
html = html.replace(/\s*<meta name="twitter:[^"]+"[^>]*>\n/g, '');

const rel = (s) => s
  .replace(/href="assets\//g, 'href="../assets/')
  .replace(/href="styles\.css/g, 'href="../styles.css')
  .replace(/href="\/favicon/g, 'href="../favicon')
  .replace(/src="assets\//g, 'src="../assets/')
  .replace(/srcset="assets\//g, 'srcset="../assets/')
  .replace(/src="gallery\.js"/g, 'src="../gallery.js"');

html = rel(html);

const banner = '<!-- Generated by scripts/sync-variant-b.mjs — do not edit by hand; edit public/index.html and re-run sync. -->\n';
const outPath = join('public', 'b', 'index.html');
writeFileSync(outPath, banner + html);
console.log(`Wrote ${outPath} (${html.length} bytes)`);